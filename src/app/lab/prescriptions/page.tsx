'use client'

import { useState, useEffect } from 'react'
import Link from 'next/link'
import { formatDateTime } from '@/lib/utils'

interface Prescription {
  id: string
  version: number
  pdfUrl: string | null
  generatedAt: string
  case: {
    id: string
    caseNumber: string
    department: string
  }
  generatedBy: {
    id: string
    name: string
  }
}

export default function PrescriptionsPage() {
  const [prescriptions, setPrescriptions] = useState<Prescription[]>([])
  const [loading, setLoading] = useState(true)
  const [showGenerate, setShowGenerate] = useState(false)
  const [genCaseId, setGenCaseId] = useState('')
  const [generating, setGenerating] = useState(false)
  const [genError, setGenError] = useState<string | null>(null)

  // Check for caseId in URL params
  useEffect(() => {
    const params = new URLSearchParams(window.location.search)
    const caseId = params.get('caseId')
    if (caseId) {
      setGenCaseId(caseId)
      setShowGenerate(true)
    }
  }, [])

  useEffect(() => {
    fetchPrescriptions()
  }, [])

  async function fetchPrescriptions() {
    setLoading(true)
    try {
      const res = await fetch('/api/prescriptions')
      if (res.ok) {
        const data = await res.json()
        setPrescriptions(data.data || [])
      }
    } catch {
      // ignore
    } finally {
      setLoading(false)
    }
  }

  async function generatePrescription(e: React.FormEvent) {
    e.preventDefault()
    if (!genCaseId) return
    setGenerating(true)
    setGenError(null)
    try {
      const res = await fetch('/api/prescriptions', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ caseId: genCaseId }),
      })
      if (res.ok) {
        setShowGenerate(false)
        setGenCaseId('')
        fetchPrescriptions()
      } else {
        const data = await res.json()
        setGenError(data.error || 'Failed to generate prescription')
      }
    } catch {
      setGenError('Failed to generate prescription')
    } finally {
      setGenerating(false)
    }
  }

  const inputClass =
    'w-full rounded-lg border border-gray-300 px-3 py-2 text-sm focus:border-brand-500 focus:outline-none focus:ring-1 focus:ring-brand-500'

  return (
    <div>
      <div className="mb-6 flex items-center justify-between">
        <div>
          <h1 className="text-2xl font-bold text-gray-900">DAMAS Prescriptions</h1>
          <p className="text-sm text-gray-500">Generate and manage DAMAS prescriptions for cases</p>
        </div>
        <button
          onClick={() => {
            setShowGenerate(true)
            setGenError(null)
          }}
          className="rounded-lg bg-brand-700 px-4 py-2 text-sm font-medium text-white hover:bg-brand-800 transition-colors"
        >
          Generate Prescription
        </button>
      </div>

      {/* Table */}
      <div className="rounded-xl border border-gray-200 bg-white overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full">
            <thead>
              <tr className="border-b border-gray-200 bg-gray-50">
                <th className="px-6 py-3 text-left text-xs font-medium uppercase text-gray-500">Case #</th>
                <th className="px-6 py-3 text-center text-xs font-medium uppercase text-gray-500">Version</th>
                <th className="px-6 py-3 text-left text-xs font-medium uppercase text-gray-500">Department</th>
                <th className="px-6 py-3 text-left text-xs font-medium uppercase text-gray-500">Generated By</th>
                <th className="px-6 py-3 text-left text-xs font-medium uppercase text-gray-500">Date</th>
                <th className="px-6 py-3 text-right text-xs font-medium uppercase text-gray-500">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-gray-100">
              {loading ? (
                <tr>
                  <td colSpan={6} className="px-6 py-12 text-center text-sm text-gray-500">
                    Loading prescriptions...
                  </td>
                </tr>
              ) : prescriptions.length === 0 ? (
                <tr>
                  <td colSpan={6} className="px-6 py-12 text-center text-sm text-gray-500">
                    No prescriptions generated yet.
                  </td>
                </tr>
              ) : (
                prescriptions.map((rx) => (
                  <tr key={rx.id} className="hover:bg-gray-50">
                    <td className="px-6 py-3">
                      <Link
                        href={`/lab/cases/${rx.case.id}`}
                        className="text-sm font-medium text-brand-700 hover:underline"
                      >
                        {rx.case.caseNumber}
                      </Link>
                    </td>
                    <td className="px-6 py-3 text-center">
                      <span className="inline-flex rounded-full bg-gray-100 px-2 py-0.5 text-xs font-medium text-gray-700">
                        v{rx.version}
                      </span>
                    </td>
                    <td className="px-6 py-3 text-sm text-gray-600">{rx.case.department}</td>
                    <td className="px-6 py-3 text-sm text-gray-600">{rx.generatedBy.name}</td>
                    <td className="px-6 py-3 text-sm text-gray-600">
                      {formatDateTime(rx.generatedAt)}
                    </td>
                    <td className="px-6 py-3 text-right">
                      <div className="flex items-center justify-end gap-2">
                        <button
                          onClick={() => alert('Prescription viewer coming soon')}
                          className="text-sm font-medium text-brand-700 hover:text-brand-800"
                        >
                          View
                        </button>
                        {rx.pdfUrl ? (
                          <a
                            href={rx.pdfUrl}
                            target="_blank"
                            rel="noopener noreferrer"
                            className="text-sm font-medium text-green-700 hover:text-green-800"
                          >
                            Download PDF
                          </a>
                        ) : (
                          <button
                            onClick={() => alert('PDF generation coming soon')}
                            className="text-sm font-medium text-gray-500 hover:text-gray-700"
                          >
                            Generate PDF
                          </button>
                        )}
                      </div>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* Generate Modal */}
      {showGenerate && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 p-4">
          <div className="w-full max-w-md rounded-xl bg-white shadow-xl">
            <div className="flex items-center justify-between border-b border-gray-200 px-6 py-4">
              <h2 className="text-lg font-semibold text-gray-900">Generate Prescription</h2>
              <button
                onClick={() => setShowGenerate(false)}
                className="rounded p-1 text-gray-400 hover:bg-gray-100 hover:text-gray-600"
              >
                <svg className="h-5 w-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
                </svg>
              </button>
            </div>

            <form onSubmit={generatePrescription} className="p-6">
              {genError && (
                <div className="mb-4 rounded-lg border border-red-200 bg-red-50 px-3 py-2 text-sm text-red-700">
                  {genError}
                </div>
              )}

              <div>
                <label className="block text-sm font-medium text-gray-700 mb-1">
                  Case ID <span className="text-red-500">*</span>
                </label>
                <input
                  type="text"
                  value={genCaseId}
                  onChange={(e) => setGenCaseId(e.target.value)}
                  placeholder="Enter case ID"
                  className={inputClass}
                  required
                />
                <p className="mt-1 text-xs text-gray-500">
                  Enter the case ID to generate a DAMAS prescription for.
                </p>
              </div>

              <div className="mt-6 flex justify-end gap-3">
                <button
                  type="button"
                  onClick={() => setShowGenerate(false)}
                  className="rounded-lg border border-gray-300 px-4 py-2 text-sm font-medium text-gray-700 hover:bg-gray-50 transition-colors"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={generating}
                  className="rounded-lg bg-brand-700 px-4 py-2 text-sm font-medium text-white hover:bg-brand-800 disabled:opacity-50 transition-colors"
                >
                  {generating ? 'Generating...' : 'Generate'}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  )
}
